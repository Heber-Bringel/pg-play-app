export class MemoryIbgeForcaDataSource implements IIbgeForcaDataSource {
  private readonly puzzles: ForcaPuzzle[];

  constructor(initialPuzzles: readonly ForcaPuzzle[] = IBGE_FORCA_PUZZLES) {
    this.puzzles = initialPuzzles.map((puzzle) => ({ ...puzzle }));
  }

  async listForcaPuzzles(): Promise<ForcaPuzzle[]> {
    try {
      return this.puzzles.map((puzzle) => ({ ...puzzle }));
    } catch {
      throw new DataSourceError('Não foi possível carregar as localidades do IBGE para a Forca.');
    }
  }
}
